"""Build docs/talk/data/bench.js (the talk's bench explorer data) from the 12-bench N=3 results.

Keeps what the explorer shows: per configuration the summary, and per run the case, pass/fail, why it failed,
tokens, latency and the transcript (user turn, tools with arguments and result codes, reply, problems).

    python3 docs/talk/tools/build_bench_data.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / "docs/iterations/12-bench/results/n3/bench.json"
OUT = ROOT / "docs/talk/data/bench.js"
LABELS = {"deepseek-official": "DeepSeek 官方", "deepseek-bailian": "DeepSeek 百炼", "qwen-bailian": "Qwen3.8-flash 百炼"}


def turn(t: dict) -> dict:
    return {
        "user": t.get("user"),
        "outcome": t.get("outcome"),
        "text": t.get("text"),
        "problems": t.get("problems") or [],
        "tools": [{"tool": x["tool"], "args": x.get("args"), "code": x.get("code")} for x in t.get("tools") or []],
        "cards": t.get("card_types") or [],
        "tickets": [t.get("tickets_before"), t.get("tickets_after")],
        "latency_s": round(t["latency_s"], 2) if t.get("latency_s") is not None else None,
        "tokens": t.get("turn_tokens"),
        "error": t.get("error"),
    }


def main() -> None:
    d = json.loads(SRC.read_text(encoding="utf-8"))
    groups = {}
    for cfg in d["configs"]:
        for name, pc in d["summaries"][cfg["id"]]["per_case"].items():
            groups[name] = pc["group"]
    out = {"meta": {k: d["meta"][k] for k in ("date", "n", "commit", "dataset_version", "prompt_version")},
           "cases": [{"name": c, "group": groups.get(c, "")} for c in d["meta"]["cases"]],
           "configs": [], "runs": {}}
    for cfg in d["configs"]:
        cid, s = cfg["id"], d["summaries"][cfg["id"]]
        out["configs"].append({
            "id": cid, "label": LABELS.get(cid, cid), "provider": cfg["provider"], "model": cfg["model"],
            "pass": s["trajectory_pass"], "runs": s["runs"], "turns": s["turns"],
            "violations": sum(s["invariant_violations"].values()), "fallback_rate": s["fallback_rate"]})
        runs = []
        for r in d["runs"][cid]:
            failures = sorted({f for tf in r["turn_failures"] for f in tf})
            runs.append({
                "case": r["case"], "i": r["index"],
                "pass": not r["crashed"] and not r["invariants"] and not any(r["turn_failures"]),
                "why": failures + [f"invariant:{k}" for k in r["invariants"]] + (["crashed"] if r["crashed"] else []),
                "tokens": r["usage"]["input"] + r["usage"]["output"],
                "turns": [turn(t) for t in r["turns"]]})
        out["runs"][cid] = runs
        # the explorer must agree with the report's own per-case counts
        for name, pc in s["per_case"].items():
            got = sum(1 for x in runs if x["case"] == name and x["pass"])
            assert got == pc["passed"], (cid, name, got, pc["passed"])
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("// generated by docs/talk/tools/build_bench_data.py from docs/iterations/12-bench/results/n3/bench.json\n"
                   "window.BENCH = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
