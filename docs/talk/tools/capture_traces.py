"""Capture real traces for the talk's trace page (docs/talk/trace.html).

Plays a few eval cases against the real model with tracing on, exporting through the app's own
`Redacting` wrapper into memory (no collector, nothing leaves this machine except the model calls),
and writes the spans to docs/talk/data/traces.js. Cost: a few tenths of a cent on deepseek-flash.

    cd backend && uv run python ../docs/talk/tools/capture_traces.py
"""
from __future__ import annotations

import asyncio
import json
import sys
import tempfile
from datetime import date
from pathlib import Path

from opentelemetry.sdk.trace.export.in_memory_span_exporter import InMemorySpanExporter

from app import tracing
from app.agent import ChatModel, LLMConfig
from evals.cases import CASES
from evals.runner import play

OUT = Path(__file__).resolve().parents[1] / "data" / "traces.js"
PICK = {  # case name → label shown in the page
    "transfer_quote": "报价：广州到利马（经三个枢纽）",
    "book_flow": "报价、确认、点击出票",
    "no_service_then_nearest": "无航线城市，改用最近的服务城市",
}


def _plain(value):
    return list(value) if isinstance(value, tuple) else value


async def main() -> int:
    memory = InMemorySpanExporter()
    provider = tracing.build({}, exporter=memory)
    tracing.use(provider)
    config = LLMConfig.from_env()
    llm = ChatModel(config)
    out, seen = [], 0
    try:
        for name, label in PICK.items():
            case = next(c for c in CASES if c.name == name)
            with tempfile.TemporaryDirectory() as tmp:
                result = await play(case, 0, llm, Path(tmp))
            provider.force_flush()
            spans = list(memory.get_finished_spans())[seen:]  # this case's spans only
            seen += len(spans)
            print(f"{name}: {'ok' if result.passed else 'FAILED'}, {len(spans)} spans", flush=True)
            traces: dict[int, list] = {}
            for s in spans:
                traces.setdefault(s.context.trace_id, []).append(s)
            turns = []
            for group in sorted(traces.values(), key=lambda g: min(s.start_time for s in g)):
                t0 = min(s.start_time for s in group)
                turns.append([{
                    "id": f"{s.context.span_id:016x}",
                    "parent": f"{s.parent.span_id:016x}" if s.parent else None,
                    "name": s.name,
                    "start_ms": round((s.start_time - t0) / 1e6, 3),
                    "dur_ms": round((s.end_time - s.start_time) / 1e6, 3),
                    "status": str(s.status.status_code).split(".")[-1],
                    "attributes": {k: _plain(v) for k, v in (s.attributes or {}).items()},
                    "events": [e.name for e in s.events],
                } for s in sorted(group, key=lambda s: s.start_time)])
            out.append({"case": name, "label": label, "passed": result.passed, "turns": turns})
    finally:
        await llm.aclose()
        tracing.use(None)
        provider.shutdown()
    payload = {"captured": date.today().isoformat(), "model": config.model, "cases": out}
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("// generated by docs/talk/tools/capture_traces.py; spans pass the app's Redacting exporter\n"
                   "window.TRACES = " + json.dumps(payload, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
    print(f"wrote {OUT}: " + ", ".join(f"{c['case']} {len(c['turns'])} traces" for c in out))
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
