"""Writes the Promptfoo config (#47 B2) from the experiment spec and the case list, so Promptfoo's
matrix (configuration × case) never drifts from `backend/evals`.

    python3 evals/promptfoo/gen.py                       # promptfooconfig.json: real mode, every configuration
    python3 evals/promptfoo/gen.py --fake --out promptfooconfig.fake.json
    options: --spec 12-bench.json  --configs a,b  --cases x,y  --max-cost 0.25  --max-tokens 5000000

Runs with the backend's Python (`backend/.venv/bin/python`); it only reads the spec and the case names."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "backend"))

from evals.cases import CASES  # noqa: E402
from evals.spec import load as load_spec  # noqa: E402


def build(spec_name: str, *, fake: bool, configs: list[str], cases: list[str], max_cost: float,
          max_tokens: int) -> dict:
    spec = load_spec(spec_name)
    chosen = [c for c in spec.configs if not configs or c.id in configs]
    picked = [c for c in CASES if not cases or c.name in cases]
    mode = "fake" if fake else "real"
    return {
        "description": f"ocean-above {spec.name}: configuration x case, {mode} mode (generated by gen.py; "
                       "one test = one whole multi-turn case with its confirmation clicks)",
        "sharing": False,
        "prompts": ["{{case}}"],
        "providers": [{
            "id": "file://provider.py",
            "label": f"{c.id}{' (fake)' if fake else ''}",
            "config": {"config_id": c.id, "spec": spec_name, "mode": mode, "max_cost": max_cost,
                       "max_tokens": max_tokens, "ledger_dir": ".promptfoo/ledger"},
        } for c in chosen],
        "defaultTest": {"assert": [
            {"type": "python", "value": "file://assertions.py:safety", "metric": "safety"},
            {"type": "python", "value": "file://assertions.py:trajectory", "metric": "trajectory"},
        ]},
        "tests": [{"description": f"{c.group}: {c.name}", "vars": {"case": c.name},
                   "metadata": {"group": c.group}} for c in picked],
        "evaluateOptions": {"maxConcurrency": 4, "cache": False},
    }


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(prog="gen.py")
    ap.add_argument("--spec", default="12-bench.json")
    ap.add_argument("--fake", action="store_true")
    ap.add_argument("--configs", default="")
    ap.add_argument("--cases", default="")
    ap.add_argument("--max-cost", type=float, default=0.25)
    ap.add_argument("--max-tokens", type=int, default=5_000_000)
    ap.add_argument("--out", default="promptfooconfig.json")
    a = ap.parse_args(argv)
    names = {c.name for c in CASES}
    cases = [x for x in a.cases.split(",") if x]
    if set(cases) - names:
        print(f"unknown cases: {sorted(set(cases) - names)}", file=sys.stderr)
        return 2
    config = build(a.spec, fake=a.fake, configs=[x for x in a.configs.split(",") if x], cases=cases,
                   max_cost=a.max_cost, max_tokens=a.max_tokens)
    if not config["providers"]:
        print("no configuration matches", file=sys.stderr)
        return 2
    (HERE / a.out).write_text(json.dumps(config, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"{a.out}: {len(config['providers'])} configuration(s) x {len(config['tests'])} case(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
